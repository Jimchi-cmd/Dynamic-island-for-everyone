//! Clipboard history (opt-in): the last few texts you copied, kept in
//! memory only (never written to disk), newest first.
//!
//! Copies that password managers mark as secret are never recorded. They
//! tag the clipboard with a marker format, and each OS has its own:
//! - Linux: `x-kde-passwordManagerHint` = "secret" (KeePassXC, KDE);
//! - macOS: the nspasteboard.org concealed/transient types (1Password,
//!   Bitwarden, KeePassXC, Strongbox…);
//! - Windows: `ExcludeClipboardContentFromMonitorProcessing`, or
//!   `CanIncludeInClipboardHistory` set to 0.

use std::collections::VecDeque;

/// Entries kept.
pub const MAX_ITEMS: usize = 20;
/// Longer copies are kept only up to this many characters.
pub const MAX_CHARS: usize = 10_000;

/// Clipboard formats that mark a copy as secret, or as not for history.
pub const SECRET_MARKERS: &[&str] = &[
    "x-kde-passwordManagerHint",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
];

/// Whether a copy offering these formats must not be recorded.
pub fn is_secret<S: AsRef<str>>(formats: &[S]) -> bool {
    formats.iter().any(|f| SECRET_MARKERS.iter().any(|m| f.as_ref().eq_ignore_ascii_case(m)))
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct History {
    items: VecDeque<String>,
}

impl History {
    /// Record a copy. Returns false when nothing changed (blank, or already
    /// the newest entry). Copying an older entry again moves it to the top.
    pub fn push(&mut self, text: &str) -> bool {
        if text.trim().is_empty() {
            return false;
        }
        let text: String = text.chars().take(MAX_CHARS).collect();
        if self.items.front() == Some(&text) {
            return false;
        }
        self.items.retain(|t| *t != text);
        self.items.push_front(text);
        self.items.truncate(MAX_ITEMS);
        true
    }

    pub fn items(&self) -> impl Iterator<Item = &String> {
        self.items.iter()
    }

    pub fn get(&self, i: usize) -> Option<&String> {
        self.items.get(i)
    }

    pub fn len(&self) -> usize {
        self.items.len()
    }

    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }

    pub fn clear(&mut self) {
        self.items.clear();
    }
}

/// One line for a list row: the first non-blank line, whitespace collapsed.
pub fn preview(text: &str) -> String {
    let line = text.lines().map(str::trim).find(|l| !l.is_empty()).unwrap_or("");
    let mut out = String::with_capacity(line.len().min(200));
    for word in line.split_whitespace() {
        if !out.is_empty() {
            out.push(' ');
        }
        out.push_str(word);
        if out.len() > 200 {
            break;
        }
    }
    if text.trim().lines().count() > 1 {
        out.push_str(" …");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn newest_first_without_duplicates() {
        let mut h = History::default();
        assert!(h.push("one"));
        assert!(h.push("two"));
        assert!(!h.push("two"), "same as the newest");
        assert!(!h.push("   \n"), "blank");
        assert!(h.push("one"), "an older copy moves to the top");
        assert_eq!(h.items().collect::<Vec<_>>(), ["one", "two"]);
        for i in 0..30 {
            h.push(&i.to_string());
        }
        assert_eq!(h.len(), MAX_ITEMS);
        assert_eq!(h.get(0).map(String::as_str), Some("29"));
        h.push(&"x".repeat(MAX_CHARS + 50));
        assert_eq!(h.get(0).unwrap().len(), MAX_CHARS);
        h.clear();
        assert!(h.is_empty());
    }

    #[test]
    fn password_manager_copies_are_secret() {
        assert!(is_secret(&["UTF8_STRING", "x-kde-passwordManagerHint"]));
        assert!(is_secret(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]));
        assert!(is_secret(&["ExcludeClipboardContentFromMonitorProcessing"]));
        assert!(!is_secret(&["UTF8_STRING", "text/plain"]));
    }

    #[test]
    fn previews() {
        assert_eq!(preview("  hello   world  "), "hello world");
        assert_eq!(preview("\n\nfn main() {\n    body\n}\n"), "fn main() { …");
        assert_eq!(preview(""), "");
    }
}
